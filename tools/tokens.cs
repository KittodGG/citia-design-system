static class Contrast
{
    static double Clamp01(double x) => Math.Min(1, Math.Max(0, x));
    static double ToLinear(double c) => c <= 0.04045 ? c / 12.92 : Math.Pow((c + 0.055) / 1.055, 2.4);
    static double ToGamma(double c) => c <= 0.0031308 ? 12.92 * c : 1.055 * Math.Pow(c, 1 / 2.4) - 0.055;

    static double[] ToOklab(double[] rgb)
    {
        var (lr, lg, lb) = (ToLinear(rgb[0]), ToLinear(rgb[1]), ToLinear(rgb[2]));
        var l = Math.Cbrt(0.4122214708 * lr + 0.5363325363 * lg + 0.0514459929 * lb);
        var m = Math.Cbrt(0.2119034982 * lr + 0.6806995451 * lg + 0.1073969566 * lb);
        var s = Math.Cbrt(0.0883024619 * lr + 0.2817188376 * lg + 0.6299787005 * lb);
        return [0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s];
    }

    static double[] FromOklab(double[] lab)
    {
        var l = Math.Pow(lab[0] + 0.3963377774 * lab[1] + 0.2158037573 * lab[2], 3);
        var m = Math.Pow(lab[0] - 0.1055613458 * lab[1] - 0.0638541728 * lab[2], 3);
        var s = Math.Pow(lab[0] - 0.0894841775 * lab[1] - 1.291485548 * lab[2], 3);
        return [Clamp01(ToGamma(4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s)), Clamp01(ToGamma(-1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s)), Clamp01(ToGamma(-0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s))];
    }

    static List<string> SplitTopLevel(string s)
    {
        var parts = new List<string>(); var depth = 0; var current = new StringBuilder();
        foreach (var ch in s)
        {
            if (ch == '(') depth++;
            if (ch == ')') depth--;
            if (ch == ',' && depth == 0) { parts.Add(current.ToString().Trim()); current.Clear(); }
            else current.Append(ch);
        }
        if (current.ToString().Trim().Length > 0) parts.Add(current.ToString().Trim());
        return parts;
    }

    public static Rgba Parse(string expr, IReadOnlyDictionary<string, string> vars, int depth = 0)
    {
        if (depth > 20) throw new InvalidOperationException($"Too deep: {expr}");
        var e = expr.Trim();
        if (e == "transparent") return new(0, 0, 0, 0);
        if (e == "black") return new(0, 0, 0, 1);
        if (e == "white") return new(1, 1, 1, 1);
        var m = Regex.Match(e, "^#([0-9a-f]{3,8})$", RegexOptions.IgnoreCase);
        if (m.Success)
        {
            var h = m.Groups[1].Value;
            if (h.Length <= 4) h = string.Concat(h.Select(c => $"{c}{c}"));
            double N(int i) => Convert.ToInt32(h.Substring(i, 2), 16) / 255.0;
            return new(N(0), N(2), N(4), h.Length == 8 ? N(6) : 1);
        }
        m = Regex.Match(e, @"^rgba?\(\s*([\d.]+)[ ,]+([\d.]+)[ ,]+([\d.]+)\s*(?:[/,]\s*([\d.]+%?))?\s*\)$", RegexOptions.IgnoreCase);
        if (m.Success)
        {
            var a = m.Groups[4].Success ? (m.Groups[4].Value.EndsWith('%') ? double.Parse(m.Groups[4].Value.TrimEnd('%')) / 100 : double.Parse(m.Groups[4].Value)) : 1;
            return new(double.Parse(m.Groups[1].Value) / 255, double.Parse(m.Groups[2].Value) / 255, double.Parse(m.Groups[3].Value) / 255, a);
        }
        m = Regex.Match(e, @"^var\(\s*(--[\w-]+)\s*(?:,\s*(.+))?\)$");
        if (m.Success)
        {
            if (vars.TryGetValue(m.Groups[1].Value, out var value)) return Parse(value, vars, depth + 1);
            if (m.Groups[2].Success) return Parse(m.Groups[2].Value, vars, depth + 1);
            throw new InvalidOperationException($"Unresolved {m.Groups[1].Value}");
        }
        m = Regex.Match(e, @"^color-mix\(\s*in\s+(oklab|srgb)\s*,(.+)\)$", RegexOptions.IgnoreCase | RegexOptions.Singleline);
        if (m.Success)
        {
            var oklab = m.Groups[1].Value.Equals("oklab", StringComparison.OrdinalIgnoreCase);
            var parts = SplitTopLevel(m.Groups[2].Value).Select(part =>
            {
                var pm = Regex.Match(part, @"^(.*?)\s+([\d.]+)%$");
                return pm.Success ? (C: Parse(pm.Groups[1].Value, vars, depth + 1), P: (double?)(double.Parse(pm.Groups[2].Value) / 100)) : (C: Parse(part, vars, depth + 1), P: (double?)null);
            }).ToList();
            double? pa = parts[0].P, pb = parts[1].P;
            if (pa is null && pb is null) { pa = 0.5; pb = 0.5; } else if (pa is null) pa = 1 - pb; else if (pb is null) pb = 1 - pa;
            var sum = pa!.Value + pb!.Value; var wa = pa.Value / sum; var wb = pb.Value / sum;
            var (ca, cb) = (parts[0].C, parts[1].C);
            var alpha = ca.A * wa + cb.A * wb;
            if (alpha == 0) return new(0, 0, 0, 0);
            double[] A = [ca.R, ca.G, ca.B], B = [cb.R, cb.G, cb.B];
            if (oklab) { A = ToOklab(A); B = ToOklab(B); }
            var mixed = A.Select((v, i) => (v * ca.A * wa + B[i] * cb.A * wb) / alpha).ToArray();
            var rgb = oklab ? FromOklab(mixed) : mixed.Select(Clamp01).ToArray();
            return new(rgb[0], rgb[1], rgb[2], alpha);
        }
        throw new InvalidOperationException($"Cannot parse colour: {e}");
    }

    public static Rgba Over(Rgba fg, Rgba bg) => new(fg.R * fg.A + bg.R * (1 - fg.A), fg.G * fg.A + bg.G * (1 - fg.A), fg.B * fg.A + bg.B * (1 - fg.A), 1);
    static double Luminance(Rgba c) => 0.2126 * ToLinear(c.R) + 0.7152 * ToLinear(c.G) + 0.0722 * ToLinear(c.B);
    public static double Ratio(Rgba x, Rgba y) { var (a, b) = (Luminance(x), Luminance(y)); return (Math.Max(a, b) + 0.05) / (Math.Min(a, b) + 0.05); }
    public static string Hex(Rgba c) => "#" + string.Concat(new[] { c.R, c.G, c.B }.Select(v => ((int)Math.Round(Clamp01(v) * 255, MidpointRounding.AwayFromZero)).ToString("x2")));
}
