    var pass = r >= min;
    if (!pass && !info) failures++;
    results.Add(new JsonObject { ["theme"] = theme, ["id"] = id, ["role"] = Bi(roleEn, roleId), ["fg"] = Contrast.Hex(fg), ["bg"] = Contrast.Hex(bg), ["ratio"] = r, ["min"] = min, ["pass"] = pass, ["informational"] = info });
    report.Append($"{(pass ? "ok  " : info ? "info" : "FAIL")} {theme,-9} {id,-24} {r.ToString("0.00"),-6} (min {min}) {Contrast.Hex(fg)} on {Contrast.Hex(bg)}\n");
}
