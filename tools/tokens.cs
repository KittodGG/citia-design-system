#!/usr/bin/env dotnet
// Citia Design System — token build. .NET 10 file-based app, no NuGet packages, no Node.
// Usage (from the repository):   dotnet run tools/tokens.cs              build everything + WCAG contrast check
//                                 dotnet run tools/tokens.cs -- --no-check
// Single source of truth: tokens/tokens.json (DTCG, English descriptions) + tokens/descriptions.id.json (Indonesian
// descriptions keyed by token path, e.g. "themes.light.color.primary", "type.title-1"). Outputs:
//   src/Citia.DesignSystem/Styles/generated/tokens.css           CSS variables per [data-theme] (+ aliases), framework-agnostic
//   src/Citia.DesignSystem/Styles/generated/tailwind-theme.css   Tailwind v4 @theme mapping (text-link, bg-popover, text-title-1, ...)
//   src/Citia.DesignSystem/Styles/generated/daisyui-themes.css   optional @plugin "daisyui/theme" blocks
//   src/Citia.DesignSystem/wwwroot/tokens/tokens.json            resolved values + bilingual descriptions for C#/JS
//   src/Citia.DesignSystem/wwwroot/tokens/contrast.json          WCAG 2.2 contrast report (exit 1 when a required pair fails)
//   src/Citia.DesignSystem/Icons/IconSet.g.cs + wwwroot/icons/sprite.svg   from wwwroot/icons/icons.json
//   docs/en/tokens.md, docs/id/tokens.md                         generated reference pages
using System.Globalization;
using System.Text;
using System.Text.Encodings.Web;
using System.Text.Json;
using System.Text.Json.Nodes;
using System.Text.RegularExpressions;

CultureInfo.CurrentCulture = CultureInfo.InvariantCulture;
var root = FindRoot(Environment.CurrentDirectory);
var src = JsonNode.Parse(File.ReadAllText(Path.Combine(root, "tokens", "tokens.json")))!.AsObject();
var idFile = Path.Combine(root, "tokens", "descriptions.id.json");
var idDescriptions = File.Exists(idFile) ? JsonNode.Parse(File.ReadAllText(idFile))!.AsObject() : new JsonObject();
var rcl = Path.Combine(root, "src", "Citia.DesignSystem");
var generatedDir = Path.Combine(rcl, "Styles", "generated");
var tokensDir = Path.Combine(rcl, "wwwroot", "tokens");
Directory.CreateDirectory(generatedDir);
Directory.CreateDirectory(tokensDir);

// Token path of every object node (for the Indonesian description lookup).
var pathOf = new Dictionary<JsonNode, string>(ReferenceEqualityComparer.Instance);
void Walk(JsonNode? node, string path)
{
    if (node is not JsonObject o) return;
    pathOf[o] = path;
    foreach (var (k, child) in o) if (!k.StartsWith('$')) Walk(child, path.Length == 0 ? k : $"{path}.{k}");
}
Walk(src, "");
string DescId(JsonObject node, string english) => pathOf.TryGetValue(node, out var p) && idDescriptions[p] is JsonNode d ? Str(d) : english;

var meta = src["$extensions"]!["ds"]!.AsObject();
var P = Str(meta["cssPrefix"]);
const string Header = "/* Generated by tools/tokens.cs from tokens/tokens.json — do not edit by hand. */\n";

/* ---------- static (theme-independent) variables ---------- */
var statics = new List<(string Name, string Value, string Desc, string DescId, string Group)>();
void Add(string name, JsonObject? node, string value, string desc, string group) => statics.Add((name, value, desc, node is null ? desc : DescId(node, desc), group));
var font = Obj(src["font"]);
foreach (var (k, n) in Entries(Obj(font["family"]))) Add($"--{P}-font-{k}", n, CssValue(n), Desc(n), "font");
foreach (var (k, n) in Entries(Obj(font["weight"]))) Add($"--{P}-weight-{k}", n, CssValue(n), Desc(n), "font");
foreach (var (role, node) in Obj(src["type"]))
{
    if (role.StartsWith('$')) continue;
    var t = Obj(node);
    var use = Str(t["use"]);
    statics.Add(($"--{P}-type-{role}-size", Str(t["size"]), use, DescId(t, use), "type"));
    statics.Add(($"--{P}-type-{role}-leading", Str(t["leading"]), "", "", "type"));
    statics.Add(($"--{P}-type-{role}-weight", Str(t["weight"]), "", "", "type"));
    statics.Add(($"--{P}-type-{role}-tracking", Str(t["tracking"]), "", "", "type"));
}
foreach (var (k, n) in Entries(Obj(src["space"]))) Add($"--{P}-space-{k}", n, CssValue(n), Desc(n), "space");
foreach (var (k, n) in Entries(Obj(src["radius"]))) Add($"--{P}-radius-{k}", n, CssValue(n), Desc(n), "radius");
foreach (var (k, n) in Entries(Obj(src["border"]))) Add($"--{P}-border-{k}", n, CssValue(n), Desc(n), "border");
foreach (var (k, n) in Entries(Obj(src["shadow"]))) Add($"--{P}-shadow-{k}", n, CssValue(n), Desc(n), "shadow");
foreach (var (k, n) in Entries(Obj(src["size"]))) Add($"--{P}-size-{k}", n, CssValue(n), Desc(n), "size");
foreach (var (k, n) in Entries(Obj(src["z"]))) Add($"--{P}-z-{k}", n, CssValue(n), Desc(n), "z");
var motion = Obj(src["motion"]);
foreach (var (k, n) in Entries(Obj(motion["duration"]))) Add($"--{P}-duration-{k}", n, CssValue(n), Desc(n), "motion");
foreach (var (k, n) in Entries(Obj(motion["easing"]))) Add($"--{P}-ease-{k}", n, CssValue(n), Desc(n), "motion");
Add($"--{P}-press-scale", Obj(motion["press-scale"]), CssValue(Obj(motion["press-scale"])), Desc(Obj(motion["press-scale"])), "motion");
Add($"--{P}-enter-offset", Obj(motion["enter-offset"]), CssValue(Obj(motion["enter-offset"])), Desc(Obj(motion["enter-offset"])), "motion");
Add($"--{P}-lift", Obj(motion["lift"]), CssValue(Obj(motion["lift"])), Desc(Obj(motion["lift"])), "motion");
foreach (var (k, n) in Entries(Obj(src["opacity"]))) Add($"--{P}-opacity-{k}", n, CssValue(n), Desc(n), "opacity");
foreach (var (k, n) in Entries(Obj(src["breakpoint"]))) Add($"--{P}-breakpoint-{k}", n, CssValue(n), Desc(n), "breakpoint");

/* ---------- themes ---------- */
Var V(string name, JsonObject n) { var d = Desc(n); return new Var(name, CssValue(n), d, DescId(n, d)); }
var shapeVars = Entries(Obj(src["shape"])).Select(e => V($"--{e.Name}", e.Node)).ToList();
var themes = new List<Theme>();
foreach (var (name, node) in Obj(src["themes"]))
{
    if (name.StartsWith('$')) continue;
    var t = Obj(node);
    var info = t["$extensions"]?["ds"]?.AsObject() ?? new JsonObject();
    themes.Add(new Theme(
        name,
        Str(info["label"] ?? name),
        Str(info["colorScheme"] ?? "light"),
        info["themeColor"] is null ? null : Str(info["themeColor"]),
        info["default"]?.GetValue<bool>() ?? false,
        info["prefersdark"]?.GetValue<bool>() ?? false,
        (info["aliases"] as JsonArray)?.Select(a => Str(a)).ToList() ?? [],
        Entries(Obj(t["color"])).Select(e => V($"--color-{e.Name}", e.Node)).ToList(),
        Entries(Obj(t["ext"])).Select(e => V($"--{P}-{e.Name}", e.Node)).ToList(),
        Entries(Obj(t["shadow"])).Select(e => V($"--{P}-shadow-{e.Name}", e.Node)).ToList()));
}
var defaultTheme = themes.FirstOrDefault(t => t.Default) ?? themes[0];
var darkTheme = themes.FirstOrDefault(t => t.PrefersDark);
List<(string, string)> ThemeLines(Theme t) =>
    [("color-scheme", t.ColorScheme), .. t.Color.Select(v => (v.Name, v.Value)), .. shapeVars.Select(v => (v.Name, v.Value)), .. t.Ext.Select(v => (v.Name, v.Value)), .. t.Shadow.Select(v => (v.Name, v.Value))];
string Selectors(Theme t) => string.Join(",\n", new[] { t.Name }.Concat(t.Aliases).Select(n => $"[data-theme=\"{n}\"]"));

var css = new StringBuilder(Header);
css.Append($"/* {Str(meta["name"])} {Str(meta["version"])} — source: {Str(meta["source"])} */\n\n");
css.Append(Block(":root", statics.Select(s => (s.Name, s.Value))));
foreach (var t in themes)
    css.Append('\n').Append(Block(t == defaultTheme ? $":root,\n{Selectors(t)}" : Selectors(t), ThemeLines(t)));
if (darkTheme is not null && darkTheme != defaultTheme)
    css.Append("\n@media (prefers-color-scheme: dark) {\n").Append(Block(":root:not([data-theme])", ThemeLines(darkTheme), "  ")).Append("}\n");
Write(Path.Combine(generatedDir, "tokens.css"), css.ToString());

/* ---------- optional daisyUI theme blocks ---------- */
var daisy = new StringBuilder(Header);
daisy.Append("/* Optional: only needed for daisyUI features that must know theme names (theme-controller). tokens.css already defines every\n   variable per [data-theme]. Standalone CLI: replace \"daisyui/theme\" with the path to .tools/daisyui-theme.mjs. */\n");
foreach (var t in themes)
{
    List<(string, string)> lines =
    [
        ("name", $"\"{t.Name}\""), ("default", t.Default ? "true" : "false"), ("prefersdark", t.PrefersDark ? "true" : "false"), ("color-scheme", t.ColorScheme),
        .. t.Color.Select(v => (v.Name, v.Value)), .. shapeVars.Select(v => (v.Name, v.Value)),
    ];
    daisy.Append('\n').Append(Block("@plugin \"daisyui/theme\"", lines));
}
Write(Path.Combine(generatedDir, "daisyui-themes.css"), daisy.ToString());

/* ---------- Tailwind v4 @theme mapping ---------- */
var twColorName = new Dictionary<string, string> { ["control-border"] = "control" };
var tw = new StringBuilder(Header);
tw.Append("/* Utilities for the extension tokens. Values resolve per element, so nested [data-theme] works. */\n@theme inline {\n");
foreach (var v in defaultTheme.Ext)
{
    var n = v.Name[$"--{P}-".Length..];
    tw.Append($"  --color-{twColorName.GetValueOrDefault(n, n)}: var(--{P}-{n});\n");
}
foreach (var v in defaultTheme.Shadow) tw.Append($"  --shadow-{v.Name[$"--{P}-shadow-".Length..]}: var({v.Name});\n");
tw.Append("}\n\n@theme {\n");
tw.Append($"  --font-sans: {CssValue(Obj(Obj(font["family"])["sans"]))};\n  --font-mono: {CssValue(Obj(Obj(font["family"])["mono"]))};\n");
foreach (var (role, node) in Obj(src["type"]))
{
    if (role.StartsWith('$')) continue;
    var t = Obj(node);
    tw.Append($"  --text-{role}: {Str(t["size"])};\n  --text-{role}--line-height: {Str(t["leading"])};\n  --text-{role}--letter-spacing: {Str(t["tracking"])};\n  --text-{role}--font-weight: {Str(t["weight"])};\n");
}
foreach (var (k, n) in Entries(Obj(src["radius"]))) if (k != "none") tw.Append($"  --radius-{k}: {CssValue(n)};\n");
foreach (var (k, n) in Entries(Obj(src["shadow"]))) if (k != "none") tw.Append($"  --shadow-{k}: {CssValue(n)};\n");
foreach (var (k, n) in Entries(Obj(motion["easing"]))) if (n["$value"] is JsonArray) tw.Append($"  --ease-{k}: {CssValue(n)};\n");
tw.Append($"  --breakpoint-xs: {CssValue(Obj(Obj(src["breakpoint"])["xs"]))};\n}}\n");
Write(Path.Combine(generatedDir, "tailwind-theme.css"), tw.ToString());

/* ---------- resolved JSON ---------- */
JsonObject Bi(string en, string id) => new() { ["en"] = en, ["id"] = id };
JsonObject VarsObject(IEnumerable<Var> vars) { var o = new JsonObject(); foreach (var v in vars) o[v.Name] = v.Value; return o; }
var resolved = new JsonObject
{
    ["name"] = Str(meta["name"]),
    ["version"] = Str(meta["version"]),
    ["source"] = Str(meta["source"]),
    ["storageKey"] = Str(meta["storageKey"]),
    ["defaultTheme"] = defaultTheme.Name,
    ["darkTheme"] = darkTheme?.Name,
    ["palette"] = new JsonObject(Entries(Obj(src["palette"])).Select(e => { var d = Desc(e.Node); return KeyValuePair.Create(e.Name, (JsonNode?)new JsonObject { ["value"] = CssValue(e.Node), ["description"] = Bi(d, DescId(e.Node, d)) }); })),
    ["themes"] = new JsonObject(themes.Select(t => KeyValuePair.Create(t.Name, (JsonNode?)new JsonObject
    {
        ["label"] = t.Label,
        ["aliases"] = new JsonArray(t.Aliases.Select(a => (JsonNode)a).ToArray()),
        ["colorScheme"] = t.ColorScheme,
        ["themeColor"] = t.ThemeColor,
        ["default"] = t.Default,
        ["prefersdark"] = t.PrefersDark,
        ["color"] = VarsObject(t.Color),
        ["ext"] = VarsObject(t.Ext),
        ["shadow"] = VarsObject(t.Shadow),
        ["descriptions"] = new JsonObject(t.Color.Concat(t.Ext).Concat(t.Shadow).Select(v => KeyValuePair.Create(v.Name, (JsonNode?)Bi(v.Desc, v.DescId)))),
    }))),
    ["shape"] = VarsObject(shapeVars),
    ["type"] = new JsonObject(Obj(src["type"]).Where(p => !p.Key.StartsWith('$')).Select(p =>
    {
        var copy = p.Value!.DeepClone().AsObject();
        var use = Str(copy["use"]);
        copy["use"] = Bi(use, DescId(Obj(p.Value), use));
        return KeyValuePair.Create(p.Key, (JsonNode?)copy);
    })),
    ["static"] = new JsonArray(statics.Select(s => (JsonNode)new JsonObject { ["name"] = s.Name, ["value"] = s.Value, ["description"] = Bi(s.Desc, s.DescId), ["group"] = s.Group }).ToArray()),
};
var jsonOptions = new JsonSerializerOptions { WriteIndented = true, Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping };
Write(Path.Combine(tokensDir, "tokens.json"), resolved.ToJsonString(jsonOptions) + "\n");

