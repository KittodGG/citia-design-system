/* ---------- helpers ---------- */
string FindRoot(string start)
{
    for (var dir = new DirectoryInfo(start); dir is not null; dir = dir.Parent)
        if (File.Exists(Path.Combine(dir.FullName, "tokens", "tokens.json"))) return dir.FullName;
    throw new InvalidOperationException("tokens/tokens.json not found. Run from inside the repository.");
}

JsonObject Obj(JsonNode? node) => node as JsonObject ?? throw new InvalidOperationException("Expected a JSON object.");
static string Str(JsonNode? node) => node is JsonValue v && v.TryGetValue<string>(out var s) ? s : node?.ToJsonString() ?? "";
static string Desc(JsonObject node) => node["$description"] is JsonNode d ? Str(d) : "";

List<(string Name, JsonObject Node)> Entries(JsonObject group, string prefix = "")
{
    var list = new List<(string, JsonObject)>();
    foreach (var (key, node) in group)
    {
        if (key.StartsWith('$') || node is not JsonObject o) continue;
        var name = prefix.Length > 0 ? $"{prefix}-{key}" : key;
        if (o.ContainsKey("$value")) list.Add((name, o));
        else list.AddRange(Entries(o, name));
    }
    return list;
}

JsonNode? Lookup(string path)
{
    JsonNode? node = src;
    foreach (var key in path.Split('.'))
    {
        node = node is JsonObject o && o.TryGetPropertyValue(key, out var next) ? next : null;
        if (node is null) return null;
    }
    return node;
}

string ValueText(JsonNode value, List<string> trail) => value switch
{
    JsonArray array => $"cubic-bezier({string.Join(", ", array.Select(x => x!.ToJsonString()))})",
    JsonValue v when v.TryGetValue<string>(out var s) => Regex.Replace(s, @"\{([^}]+)\}", m =>
    {
        var path = m.Groups[1].Value;
        if (trail.Contains(path)) throw new InvalidOperationException($"Circular token reference: {string.Join(" -> ", trail)} -> {path}");
        if (Lookup(path) is not JsonObject target || !target.ContainsKey("$value")) throw new InvalidOperationException($"Unknown token reference {{{path}}}");
        return ValueText(target["$value"]!, [.. trail, path]);
    }),
    _ => value.ToJsonString(),
};
string CssValue(JsonObject node) => ValueText(node["$value"]!, []);

static string Block(string selector, IEnumerable<(string Key, string Value)> lines, string indent = "")
{
    var sb = new StringBuilder($"{indent}{selector} {{\n");
    foreach (var (k, v) in lines) sb.Append($"{indent}  {k}: {v};\n");
    return sb.Append($"{indent}}}\n").ToString();
}

static void Write(string path, string content)
{
    Directory.CreateDirectory(Path.GetDirectoryName(path)!);
    File.WriteAllText(path, content.Replace("\r\n", "\n"), new UTF8Encoding(false));
}

