static string Esc(string s) => s.Replace("|", "\\|").Replace("\n", " ");
static string Code(string v) => $"`{(Regex.IsMatch(v, "^#[0-9a-f]{3,8}$", RegexOptions.IgnoreCase) ? v : Esc(v))}`";
