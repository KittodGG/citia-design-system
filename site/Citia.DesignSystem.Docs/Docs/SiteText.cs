    public static string T(string lang, string key, params object?[] args)
    {
        var text = Text.TryGetValue(lang, out var table) && table.TryGetValue(key, out var v) ? v
            : Text["en"].TryGetValue(key, out var en) ? en : key;
        return args.Length == 0 ? text : string.Format(text, args);
    }

    public static bool Has(string lang) => Text.ContainsKey(lang);
